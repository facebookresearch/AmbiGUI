"""Tell apart a task the policy failed from a page it was never allowed to attempt.

Probed on 2026-10-01, 62 of 182 held-out ask-eval rows (34.1%) and 227 of 706 training
rows (32.2%) boot onto a page Chromium cannot use — mostly HTTP 403 bot walls and
CloudFront error bodies served to a datacentre IP range. The navigation itself succeeds,
so ``goto`` returns and the environment marks the boot healthy; the agent is then asked to
complete a booking on an error page whose only available actions are ``ask`` and ``stop``.

Those two fractions are dated because a wall can lift: a probe one day earlier found 61
rather than 62 blocked. They describe the stores at that date, not a constant.

These rows are a different population, not noise to be averaged in. On them a policy is
structurally prevented from acting, and every clarifying question it asks is scored
irrelevant because none of them names a task parameter. Averaging the two together makes
neither readable, so the rows are classified, partitioned and reported separately.

Two things the obvious checks get wrong, and why this module exists:

* **A screenshot test passes.** The store builder accepted a page whose screenshot was
  not one flat colour. An error page has text and a logo.
* **An HTTP probe disagrees with a browser.** ``rentalcars.com`` answered 200 to an HTTP
  client while Chromium got a CloudFront error page. Only a browser verdict counts, which
  is why :class:`PageProbe` is filled by one.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum
from typing import Any


class BlockerKind(str, Enum):
    """Why a page cannot be worked on. ``OK`` means it can."""

    OK = "ok"
    BOT_WALL = "bot_wall_403"
    CLOUDFRONT = "cloudfront_error"
    INTERSTITIAL = "captcha_interstitial"
    CONNECT_FAIL = "dns_or_connect_fail"
    NAV_TIMEOUT = "nav_timeout"
    NO_INTERACTIVE = "no_interactive_elements"
    BAD_STATUS = "bad_http_status"


@dataclass(frozen=True)
class PageProbe:
    """What a real browser saw at a start URL."""

    url: str
    final_url: str
    status: int | None
    title: str
    text: str
    n_interactive: int
    error: str | None


@dataclass(frozen=True)
class BlockerVerdict:
    """Whether the page is usable, which kind of wall it is, and the evidence."""

    blocked: bool
    kind: BlockerKind
    evidence: str


#: Substrings that identify a CloudFront denial body. Matched case-insensitively.
_CLOUDFRONT = ("generated by cloudfront", "the request could not be satisfied")

#: Substrings that identify a bot-check interstitial, in the title or the body.
_INTERSTITIAL = (
    "just a moment",
    "verify you are human",
    "verifying you are human",
    "verifying the device",
    "access denied",
    "pardon our interruption",
    "are you a robot",
    "enable javascript and cookies to continue",
    "checking your browser",
)

_BLOCKING_STATUS = frozenset({401, 403, 429})

#: The only status a page a policy may act on is served with.
OK_STATUS = 200


def status_is_usable(status: int | None) -> bool:
    """Whether a start page's HTTP status allows a policy to act on it.

    ``None`` means the navigation reported no status. That is not evidence of a
    refusal, so it is usable here and left to the other rules.
    """
    return status is None or status == OK_STATUS


def classify_page(probe: PageProbe) -> BlockerVerdict:
    """Decide whether ``probe`` describes a page a policy could act on.

    Order matters. A bot wall usually also has no interactive elements, and reporting it
    as the vaguer symptom would lose the reason. The specific causes are therefore tested
    first and the interactive-element count is the catch-all.
    """
    if probe.error:
        low = probe.error.lower()
        kind = BlockerKind.NAV_TIMEOUT if "timeout" in low else BlockerKind.CONNECT_FAIL
        return BlockerVerdict(True, kind, probe.error)

    haystack = f"{probe.title}\n{probe.text}".lower()

    if any(marker in haystack for marker in _CLOUDFRONT):
        return BlockerVerdict(True, BlockerKind.CLOUDFRONT, probe.title[:120])
    if probe.status in _BLOCKING_STATUS:
        return BlockerVerdict(True, BlockerKind.BOT_WALL, f"HTTP {probe.status}")
    if any(marker in haystack for marker in _INTERSTITIAL):
        return BlockerVerdict(True, BlockerKind.INTERSTITIAL, probe.title[:120])
    if not status_is_usable(probe.status):
        # Anything the site did not serve normally. The named walls above are tested
        # first so they keep their specific reason; this catches the rest, so a status
        # nobody listed does not read as a usable page. A status of ``None`` means the
        # navigation reported none, which is not evidence of a wall, so it is left to
        # the interactive-element rule below.
        return BlockerVerdict(True, BlockerKind.BAD_STATUS, f"HTTP {probe.status}")
    if probe.n_interactive == 0:
        return BlockerVerdict(
            True,
            BlockerKind.NO_INTERACTIVE,
            "no clickable or typeable element on the page",
        )
    return BlockerVerdict(
        False, BlockerKind.OK, f"HTTP {probe.status}, {probe.n_interactive} elements"
    )


def start_page_verdict(env: Any) -> BlockerVerdict:
    """Whether a policy can act on the page this environment just reset onto.

    Both the evaluation and the training rollout call this. One call, so the two
    cannot classify one page two ways. On the active store 18.1% of 237 start URLs
    are blocked.
    """
    return classify_page(env.start_page_probe())
